/** Device types whose every value only reports. A wrong guess must not open a door, and these only detect or watch anyway. */
const REPORT_ONLY_KINDS = ["sensor", "lock"];
const REPORT_ONLY_TYPES = ["smoke-sensor", "gas-sensor", "submersion-sensor", "camera", "video-doorbell", "doorbell", "intercom", "driving-recorder", "electric-power", "tracker"];

/** The <type> in urn:miot-spec-v2:device:<type>:... */
export function deviceType(urn: string): string {
  return urn.split(":")[3] ?? "";
}

export function kindOf(type: string): string {
  return Object.prototype.hasOwnProperty.call(DEVICE_KINDS, type) ? DEVICE_KINDS[type] : "other";
}

export function reportOnly(type: string): boolean {
  return REPORT_ONLY_KINDS.includes(kindOf(type)) || REPORT_ONLY_TYPES.includes(type);
}
